import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
import { mkdir } from 'node:fs/promises'
const url = (process.env.PCI_BROWSER_URL || 'http://127.0.0.1:3000').replace(/\/$/, '')
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${url}/animation-preview/`, { waitUntil: 'domcontentloaded' })
  await page.locator('video').scrollIntoViewIfNeeded()
  await page.waitForFunction(() => document.querySelector('video')?.currentTime > .2)
  const metadata = await page.locator('video').evaluate(video => ({ duration: video.duration, width: video.videoWidth, height: video.videoHeight }))
  assert.ok(Math.abs(metadata.duration - 12.28) < .05)
  assert.equal(metadata.width, 1280)
  assert.equal(metadata.height, 720)
  await page.getByRole('button', { name: 'PCI branding', exact: true }).click()
  assert.match(await page.locator('video source').first().getAttribute('src'), /branded/)
  await page.setViewportSize({ width: 390, height: 844 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  assert.equal(await page.locator('video').evaluate(video => getComputedStyle(video).display), 'none')
  assert.equal(await page.locator('.pci-cable-poster').evaluate(image => image.complete && image.naturalWidth > 0), true)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(url)
  const section = page.locator('section[aria-labelledby="product-film-heading"]')
  const film = section.locator('video')
  const copy = section.locator('[data-film-entrance]')
  await section.locator('[data-film-entrance="waiting"]').waitFor()
  await copy.evaluate(element => {
    const delays = []
    element.addEventListener('animationstart', event => {
      if (event.target.parentElement !== element) return
      delays.push(getComputedStyle(event.target).animationDelay)
      element.dataset.testEntranceDelays = delays.join(',')
    })
  })
  await copy.scrollIntoViewIfNeeded()
  await section.locator('[data-film-entrance="settled"]').waitFor()
  assert.equal(await copy.getAttribute('data-test-entrance-delays'), '0s,0.09s,0.18s')
  await film.scrollIntoViewIfNeeded()
  await page.waitForFunction(() => document.querySelector('section[aria-labelledby="product-film-heading"] video')?.currentTime > .2)
  assert.match(await film.locator('source').first().getAttribute('src'), /pci-reference-aluminum-clean/)
  assert.equal(await film.evaluate(video => !video.controls && video.muted && video.playsInline), true)
  assert.equal(await section.locator('.product-grid').count(), 0)
  const catalogue = section.getByRole('link', { name: 'View all 14 products' })
  assert.equal(await catalogue.getAttribute('href'), '/products/')
  const desktopCopy = await copy.boundingBox()
  const desktopFilm = await film.boundingBox()
  assert.ok(desktopCopy.x < desktopFilm.x && desktopCopy.x + desktopCopy.width > desktopFilm.x, 'Desktop copy overlaps the left edge of the film')
  await catalogue.click({ trial: true })
  const toggle = section.locator('.pci-cable-toggle')
  await toggle.hover({ position: { x: desktopFilm.width * .7, y: 70 } })
  assert.equal(await film.evaluate(video => video.paused), false, 'Hover does not pause')
  await page.waitForFunction(() => document.querySelector('.pci-cable-interactive').style.getPropertyValue('--cable-ry') !== '')
  await toggle.click()
  assert.equal(await film.evaluate(video => video.paused), true)
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  await page.waitForTimeout(200)
  await toggle.scrollIntoViewIfNeeded()
  await page.waitForTimeout(200)
  assert.equal(await film.evaluate(video => video.paused), true, 'Intentional pause survives leaving and re-entering')
  assert.equal(await copy.getAttribute('data-film-entrance'), 'settled', 'The entrance plays once')
  assert.equal(await copy.getAttribute('data-test-entrance-delays'), '0s,0.09s,0.18s')
  await toggle.focus()
  await page.keyboard.press('Enter')
  await page.waitForFunction(() => !document.querySelector('.pci-cable-interactive video').paused)
  await page.keyboard.press('Space')
  assert.equal(await film.evaluate(video => video.paused), true, 'Keyboard toggles playback')
  await page.waitForFunction(() => document.querySelector('.pci-cable-interactive').style.getPropertyValue('--cable-ry') === '')
  await film.evaluate(video => { video.currentTime = 5 })
  await page.waitForFunction(() => !document.querySelector('section[aria-labelledby="product-film-heading"] video').seeking)
  await mkdir('test-results', { recursive: true })
  const hideChrome = await page.addStyleTag({ content: '.site-head,.info-trigger,.skip{visibility:hidden!important}' })
  await toggle.evaluate(element => element.blur())
  await page.mouse.move(0, 0)
  await section.screenshot({ path: 'test-results/product-film-desktop.png' })
  for (const time of [1, 9]) {
    await film.evaluate((video, time) => { video.currentTime = time }, time)
    await page.waitForFunction(() => !document.querySelector('.pci-cable-interactive video').seeking)
    await section.screenshot({ path: `test-results/product-film-desktop-${time}.png` })
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await section.screenshot({ path: 'test-results/product-film-mobile.png' })
  const mobileCopy = await copy.boundingBox()
  const mobileFilm = await film.boundingBox()
  assert.ok(mobileCopy.y + mobileCopy.height <= mobileFilm.y, 'Mobile copy sits above the film')
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await hideChrome.evaluate(style => style.remove())
  await toggle.click()
  await page.waitForFunction(() => !document.querySelector('.pci-cable-interactive video').paused)
  await page.evaluate(() => { document.documentElement.dataset.pciMotion = 'paused' })
  assert.equal(await film.evaluate(video => video.paused), false, 'Foreground film continues when background motion is paused')
  assert.notEqual(await film.evaluate(video => getComputedStyle(video).display), 'none')
  await page.evaluate(() => { document.documentElement.dataset.pciMotion = '' })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.waitForFunction(() => document.querySelector('section[aria-labelledby="product-film-heading"] video').paused)
  assert.equal(await film.evaluate(video => getComputedStyle(video).display), 'none')
  assert.equal(await toggle.count(), 1, 'Reduced motion keeps a manual play option')
  await toggle.click()
  await page.waitForFunction(() => !document.querySelector('.pci-cable-interactive video').paused)
  assert.notEqual(await film.evaluate(video => getComputedStyle(video).display), 'none')
  await page.setViewportSize({ width: 720, height: 475 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, '200% effective viewport fits')
  const touch = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  await touch.goto(url)
  const touchToggle = touch.locator('.pci-cable-toggle')
  await touchToggle.scrollIntoViewIfNeeded()
  await touch.waitForFunction(() => !document.querySelector('.pci-cable-interactive video').paused)
  await touchToggle.tap()
  assert.equal(await touch.locator('.pci-cable-interactive video').evaluate(video => video.paused), true)
  await touchToggle.tap()
  await touch.waitForFunction(() => !document.querySelector('.pci-cable-interactive video').paused)
  assert.equal(await touch.locator('.pci-cable-interactive').evaluate(element => element.style.getPropertyValue('--cable-ry')), '')
  await touch.close()
  const savedPause = await browser.newPage()
  await savedPause.addInitScript(() => localStorage.setItem('pci-pause-motion', 'yes'))
  await savedPause.goto(url)
  await savedPause.locator('.pci-cable-interactive video').scrollIntoViewIfNeeded()
  await savedPause.waitForFunction(() => document.querySelector('.pci-cable-interactive video')?.currentTime > .2)
  assert.equal(await savedPause.locator('html').getAttribute('data-pci-motion'), 'paused')
  assert.equal(await savedPause.locator('[data-film-entrance]').getAttribute('data-film-entrance'), 'settled')
  await savedPause.close()
  const reduced = await browser.newPage({ reducedMotion: 'reduce' })
  await reduced.goto(url)
  const reducedCopy = reduced.locator('[data-film-entrance]')
  await reducedCopy.scrollIntoViewIfNeeded()
  assert.equal(await reducedCopy.getAttribute('data-film-entrance'), 'settled')
  assert.equal(await reducedCopy.locator('h2').evaluate(element => getComputedStyle(element.parentElement).opacity), '1')
  await reduced.emulateMedia({ reducedMotion: 'no-preference' })
  await reduced.goto(url)
  await reduced.locator('[data-film-entrance="waiting"]').waitFor()
  await reducedCopy.evaluate(element => {
    const observer = new MutationObserver(() => {
      if (element.dataset.filmEntrance !== 'running') return
      observer.disconnect()
      element.querySelector('a').focus()
    })
    observer.observe(element, { attributes: true, attributeFilter: ['data-film-entrance'] })
  })
  await reducedCopy.scrollIntoViewIfNeeded()
  await reduced.locator('[data-film-entrance="settled"] a:focus').waitFor()
  assert.equal(await reducedCopy.locator('a').evaluate(element => getComputedStyle(element.parentElement).opacity), '1')
  await reduced.close()
  const fallback = await browser.newPage({ javaScriptEnabled: false })
  await fallback.goto(url)
  assert.equal(await fallback.locator('.pci-cable-toggle').count(), 0)
  assert.equal(await fallback.locator('.pci-cable-interactive .pci-cable-poster').count(), 1)
  assert.equal(await fallback.locator('[data-film-entrance]').getAttribute('data-film-entrance'), 'settled')
  await fallback.close()
  const blocked = await browser.newPage()
  await blocked.addInitScript(() => {
    const original = HTMLMediaElement.prototype.play
    let attempts = 0
    HTMLMediaElement.prototype.play = function() {
      if (++attempts === 1) return Promise.reject(new DOMException('Autoplay blocked', 'NotAllowedError'))
      return original.call(this)
    }
  })
  await blocked.goto(url)
  const blockedToggle = blocked.locator('.pci-cable-toggle')
  await blockedToggle.scrollIntoViewIfNeeded()
  await blocked.waitForTimeout(200)
  assert.equal(await blocked.locator('.pci-cable-interactive video').evaluate(video => video.paused), true)
  await blockedToggle.click()
  await blocked.waitForFunction(() => document.querySelector('.pci-cable-interactive video').currentTime > .1)
  await blocked.locator('.pci-cable-interactive video').evaluate(video => video.dispatchEvent(new Event('error')))
  await blocked.waitForFunction(() => !document.querySelector('.pci-cable-interactive video'))
  assert.equal(await blockedToggle.count(), 0)
  assert.equal(await blocked.locator('.pci-cable-interactive .pci-cable-poster').isVisible(), true)
  await blocked.close()
  assert.deepEqual(errors, [])
  console.log('Reference film and homepage showcase: playback, catalogue link, desktop/mobile layout, and motion fallback passed.')
} finally { await browser.close() }
