import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { chromium } from 'playwright-core'
const require = createRequire(import.meta.url)
const browser = await chromium.launch({executablePath:process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe'})
const url = process.env.PCI_BROWSER_URL || 'http://127.0.0.1:3000/'
await mkdir('test-results',{recursive:true})
const errors = []
async function open(options={}) {
  const page = await browser.newPage({viewport:{width:1440,height:950},...options})
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto(url,{waitUntil:'networkidle'})
  return page
}
async function progress(page,p) {
  await page.evaluate(p=>{
    const el = document.querySelector('.about-cable')
    const header = document.querySelector('.site-head').offsetHeight
    window.scrollTo({top:scrollY+el.getBoundingClientRect().top-header+(el.offsetHeight-(innerHeight-header))*p,behavior:'instant'})
  },p)
  await page.waitForTimeout(280)
}
const opacity = (page,selector)=>page.locator(selector).evaluate(el=>Number(getComputedStyle(el).opacity))
const overflow = page=>page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)
try {
  const page = await open()
  assert.equal(await page.locator('.about-cable').getAttribute('data-mode'),'cinematic')
  await progress(page,0)
  await page.locator('.cable-webgl[data-ready=yes] canvas').waitFor()
  const first3DFrame = await page.locator('.cable-webgl canvas').screenshot()
  await progress(page,.35)
  const next3DFrame = await page.locator('.cable-webgl canvas').screenshot()
  assert.equal(first3DFrame.equals(next3DFrame),false,'Live geometry changes with scroll')
  await progress(page,0)
  const centre = await page.locator('.conductor-main').boundingBox()
  assert.ok(Math.abs(centre.x+centre.width/2-720)<85,'Cable group starts in the middle')
  assert.equal(await opacity(page,'.line-one'),0,'Story waits for the product group to move')
  for (const [label,p] of [['arrival',0],['opening',.35],['headline',.66],['finished',.9]]) {
    await progress(page,p)
    await page.screenshot({path:`test-results/about-${label}.png`})
  }
  assert.equal(await opacity(page,'.about-description'),1,'Copy fully revealed')
  const left = await page.locator('.conductor-main').boundingBox()
  assert.ok(centre.x-left.x>150,'Cable group moves left before the story is fully shown')
  assert.equal(await page.locator('.conductor-main img').evaluate(el=>el.complete && el.naturalWidth>0),true,'Cable artwork loaded')
  assert.equal(await opacity(page,'.satellite-two'),1,'Companion products revealed')
  assert.equal(await page.locator('.conductor-references img').count(),3,'Original product images remain in the scene')
  await progress(page,.1)
  assert.equal(await opacity(page,'.satellite-one'),0,'Reverse scrolling retracts companion products')
  assert.equal(await opacity(page,'.satellite-two'),0,'Reverse scrolling retracts the second product')
  assert.equal(await opacity(page,'.line-three'),0,'Reverse scrolling reverses text reveal')
  await progress(page,.9)
  await page.reload({waitUntil:'networkidle'})
  assert.equal(await opacity(page,'.about-description'),1,'Reload restores scroll composition')
  await page.addScriptTag({path:require.resolve('axe-core/axe.min.js')})
  const violations = await page.evaluate(async()=> (await window.axe.run('.about-cable',{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa','wcag22aa']}})).violations)
  assert.deepEqual(violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)})),[],'About accessibility')
  await progress(page,.2)
  await page.locator('.about-skip').focus()
  await page.keyboard.press('Enter')
  assert.equal(await page.locator('.about-cable').getAttribute('data-mode'),'static')
  assert.equal(await page.locator('#about-pci-title').evaluate(el=>el===document.activeElement),true,'Skip moves focus')
  assert.equal(await opacity(page,'.about-description'),1)
  const keyboard = await open()
  await progress(keyboard,.2)
  await keyboard.locator('.about-skip').focus()
  await keyboard.keyboard.press('Tab')
  assert.equal(await opacity(keyboard,'.about-description'),1,'Keyboard focus reveals story link')
  const paused = await open()
  await progress(paused,.5)
  await paused.getByRole('button',{name:'Quick info'}).click()
  await paused.getByLabel('Pause background motion').check()
  await paused.keyboard.press('Escape')
  assert.equal(await paused.locator('.about-cable').getAttribute('data-mode'),'static')
  assert.equal(await opacity(paused,'.about-description'),1)
  await paused.reload({waitUntil:'networkidle'})
  assert.equal(await paused.locator('.about-cable').getAttribute('data-mode'),'static','Saved motion preference')
  const reduced = await open({reducedMotion:'reduce'})
  assert.equal(await reduced.locator('.about-cable').getAttribute('data-mode'),'static')
  const mobile = await open({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
  await mobile.locator('.about-cable').scrollIntoViewIfNeeded()
  assert.equal(await mobile.locator('.about-cable').getAttribute('data-mode'),'flow')
  assert.equal(await overflow(mobile),false)
  await mobile.screenshot({path:'test-results/about-mobile.png',fullPage:false})
  await mobile.locator('.about-cable').screenshot({path:'test-results/about-mobile-section.png'})
  const noJS = await open({javaScriptEnabled:false})
  assert.equal(await opacity(noJS,'.about-description'),1,'No-JavaScript readable copy')
  assert.equal(await noJS.locator('.about-skip').isVisible(),false)
  const noGPU = await open({})
  await progress(noGPU,.9)
  await noGPU.locator('.cable-webgl[data-ready=yes] canvas').waitFor()
  await noGPU.locator('.cable-webgl canvas').evaluate(canvas=>canvas.getContext('webgl2').getExtension('WEBGL_lose_context').loseContext())
  await noGPU.waitForFunction(()=>!document.querySelector('.cable-webgl')?.hasAttribute('data-ready'))
  await noGPU.waitForTimeout(350)
  assert.equal(await opacity(noGPU,'.cable-fallback'),1,'Artwork replaces a lost WebGL context')
  await page.setViewportSize({width:720,height:475})
  assert.equal(await overflow(page),false,'200 percent equivalent viewport has no overflow')
  assert.equal(await opacity(page,'.about-description'),1)
  const resized = await open()
  await progress(resized,.6)
  await resized.setViewportSize({width:800,height:650})
  assert.equal(await resized.locator('.about-cable').getAttribute('data-mode'),'flow')
  assert.equal(await opacity(resized,'.about-description'),1)
  assert.deepEqual(errors,[])
  console.log('About: forward/reverse, reload, keyboard, pause, reduced motion, mobile, resize, no-JS and accessibility passed.')
} finally {await browser.close()}
