const errors = []
async function open(options={}) {
  const page = await browser.newPage({viewport:{width:1440,height:950},...options})
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto(url,{waitUntil:'networkidle'})
  return page
}
async function progress(page,p) {
  await page.evaluate(p=>{
    const el = document.querySelector('.about-cable')
    const header = document.querySelector('.site-head').offsetHeight
    window.scrollTo({top:scrollY+el.getBoundingClientRect().top-header+(el.offsetHeight-(innerHeight-header))*p,behavior:'instant'})
  },p)
  await page.waitForTimeout(320)
}
const opacity = (page,selector)=>page.locator(selector).first().evaluate(el=>Number(getComputedStyle(el).opacity))
const overflow = page=>page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)
const axe = async (page,context='.about-cable')=>{
  if (!await page.evaluate(()=>'axe' in window)) await page.addScriptTag({path:require.resolve('axe-core/axe.min.js')})
  const violations = await page.evaluate(async context=>(await window.axe.run(context,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa','wcag22aa']}})).violations,context)
  return violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)}))
}
/** Anatomy labels must not collide with each other, must stay on screen, and leaders must start on the cable canvas. */
async function checkAnatomy(page,size) {
  await page.waitForFunction(()=>document.querySelector('.about-art')?.dataset.anchors==='live')
  const report = await page.evaluate(()=>{
    const labels=[...document.querySelectorAll('.anatomy li')].map(li=>({name:li.dataset.anchor,o:Number(getComputedStyle(li).opacity),r:li.getBoundingClientRect().toJSON()}))
    const art=document.querySelector('.about-art').getBoundingClientRect(), canvas=document.querySelector('.cable-webgl canvas').getBoundingClientRect()
    const starts=[...document.querySelectorAll('[data-anchor-line]')].map(path=>{const [x,y]=path.getAttribute('d').slice(1).split('L')[0].split(' ').map(Number);return {x:art.left+x,y:art.top+y}})
    return {labels,canvas:canvas.toJSON(),starts,width:innerWidth,height:innerHeight}
  })
  assert.equal(report.labels.length,5,`${size}: five anatomy layers`)
  for (const l of report.labels) {
    assert.ok(l.o>.95,`${size}: ${l.name} label visible`)
    assert.ok(l.r.left>=0 && l.r.right<=report.width && l.r.top>=0 && l.r.bottom<=report.height,`${size}: ${l.name} label on screen`)
  }
  for (let i=0;i<5;i++) for (let j=i+1;j<5;j++) {
    const a=report.labels[i].r,b=report.labels[j].r
    assert.ok(a.right<=b.left||b.right<=a.left||a.bottom<=b.top||b.bottom<=a.top,`${size}: ${report.labels[i].name} and ${report.labels[j].name} labels do not overlap`)
  }
  const c=report.canvas
  for (const s of report.starts) assert.ok(s.x>=c.left&&s.x<=c.right&&s.y>=c.top&&s.y<=c.bottom,`${size}: leader starts on the cable`)
}
